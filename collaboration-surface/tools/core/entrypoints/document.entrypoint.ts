import { spawnSync } from "node:child_process";
import { resolve } from "node:path";

import { isResolved, projectRoot, slotList, surfacePrefix } from "../../../config/surface.config.ts";

const REPO_ROOT = projectRoot();

const SLOT = "document_generators";

const RUNTIME = process.execPath;

function main(): number {
    if (!isResolved("execution", SLOT)) {
        process.stdout.write(
            "ABSENT  this host declares no document generator, so the branch that would run one DOES NOT RUN rather " +
                "than failing. A slot with no analogue resolves ABSENT and the consumer declares that state — an entry " +
                "document generated by a capability the host does not carry is a demand nothing can satisfy, and a " +
                "package that reported a failure here would be asserting a defect in a host for not having something " +
                "this package never provided\n",
        );
        return 0;
    }

    const declared = slotList("execution", SLOT);
    const cwd = resolve(REPO_ROOT, surfacePrefix());

    for (const invocation of declared) {
        const argv = invocation.split(" ").filter((token) => token.length > 0);
        process.stdout.write(`RUNNING  ${invocation}\n`);

        const outcome = spawnSync(RUNTIME, argv, { cwd, stdio: "inherit" });
        if (outcome.status === 0) continue;

        process.stdout.write(
            `FAILED  ${invocation} exited ${String(outcome.status)}. THE INVOCATION IS RESOLVED FROM A SLOT RATHER ` +
                "THAN SPELLED AT A CALL SITE, so what failed is the host capability rather than a path this package " +
                "composed — and it runs from the surface root rather than from the caller's working directory, which " +
                "is the fragility a relative literal in a script carries and a slot does not\n",
        );
        return 1;
    }

    process.stdout.write(
        `GENERATED  ${String(declared.length)} host document generator(s) ran from the surface root\n`,
    );
    return 0;
}

process.exit(main());
